import pandas as pd

class Instrument:
    def __init__(self, df: pd.DataFrame):
        self.odf = df
        self.df = df.copy()
        self._validate_df()

    def _validate_df(self):
        required_columns = {'date', 'open', 'high', 'low', 'close'}
        if not required_columns.issubset(self.df.columns):
            raise ValueError("DataFrame must contain 'date', 'open', 'high', 'low', 'close' columns")

class Renko(Instrument):
    PERIOD_CLOSE = 1
    PRICE_MOVEMENT = 2
    TREND_CHANGE_DIFF = 3

    def __init__(self, df: pd.DataFrame, brick_size: int, chart_type: int):
        super().__init__(df)
        self.brick_size = brick_size
        self.chart_type = chart_type

    def get_ohlc_data(self) -> pd.DataFrame:
        if self.chart_type == self.PERIOD_CLOSE:
            return self.period_close_bricks()
        else:
            self.price_movement_bricks()
            return self.shift_bricks()

    def price_movement_bricks(self):
        self.df['close_diff'] = self.df['close'].diff()
        self.df['direction'] = self.df['close_diff'].apply(lambda x: 1 if x > 0 else -1)
        self.df['abs_diff'] = self.df['close_diff'].abs()
        self.df['bricks'] = self.df['abs_diff'] // self.brick_size
        self.df['cumulative_bricks'] = self.df['bricks'].cumsum()
        self.df['brick_price'] = self.df['close'].iloc[0] + self.df['cumulative_bricks'] * self.brick_size * self.df['direction']

    def shift_bricks(self) -> pd.DataFrame:
        self.df['shifted_brick_price'] = self.df['brick_price'].shift(1)
        self.df['brick_change'] = self.df['brick_price'] - self.df['shifted_brick_price']
        self.df['brick_change'] = self.df['brick_change'].fillna(0)
        self.df['brick_change'] = self.df['brick_change'].apply(lambda x: self.brick_size if x > 0 else -self.brick_size if x < 0 else 0)
        self.df['final_brick_price'] = self.df['brick_price'].iloc[0] + self.df['brick_change'].cumsum()
        return self.df[['date', 'final_brick_price']].rename(columns={'final_brick_price': 'close'})

    def period_close_bricks(self) -> pd.DataFrame:
        self.df['close_diff'] = self.df['close'].diff()
        self.df['direction'] = self.df['close_diff'].apply(lambda x: 1 if x > 0 else -1)
        self.df['abs_diff'] = self.df['close_diff'].abs()
        self.df['bricks'] = self.df['abs_diff'] // self.brick_size
        self.df['cumulative_bricks'] = self.df['bricks'].cumsum()
        self.df['brick_price'] = self.df['close'].iloc[0] + self.df['cumulative_bricks'] * self.brick_size * self.df['direction']
        return self.df[['date', 'brick_price']].rename(columns={'brick_price': 'close'})

